def normalize_slug(url: str) -> str:
    s = str(url).lower().strip().replace('.git', '').rstrip('/')
    if 'github.com/' in s:
        return s.split('github.com/')[-1]
    if 'api.github.com/repos/' in s:
        return s.split('api.github.com/repos/')[-1]
    parts = s.split('/')
    if len(parts) >= 2:
        return f"{parts[-2]}/{parts[-1]}"
    return s


def main():
    print("=" * 70)
    print("ATTRIBUTION VALIDATION")
    print("=" * 70)
    print(f"Sample size : {SAMPLE_SIZE} PRs (stratified by repository)")
    print(f"Random seed : {RANDOM_SEED}")
    print()

    # Load cohort
    df_repos = pd.read_csv(INPUT_REPOS)
    slugs    = set(df_repos['slug'].unique())
    print(f"Cohort: {len(slugs)} repositories")

    # Load human PRs
    df_human = pd.read_parquet(INPUT_HUMAN)
    url_col  = next(
        c for c in ['repo_url', 'url', 'repository_url']
        if c in df_human.columns
    )
    df_human['slug'] = df_human[url_col].apply(normalize_slug)
    df_human = df_human[df_human['slug'].isin(slugs)].copy()
    print(f"Human PRs in cohort: {len(df_human):,}")
    print()

    # Stratified sample
    print(f"Sampling {SAMPLE_SIZE} PRs stratified by repository...")
    sample = stratified_sample(df_human, SAMPLE_SIZE, 'slug', RANDOM_SEED)
    print(f"Sample size achieved: {len(sample)}")
    print()

    # Classify each PR
    print("Classifying PRs by AI-assistance signal strength...")
    classifications = sample.apply(classify_pr, axis=1)
    class_df = pd.DataFrame(classifications.tolist())
    sample   = pd.concat([sample, class_df], axis=1)

    # Add GitHub URL for manual review
    sample['github_url'] = sample['html_url']

    # Print tier distribution
    print()
    print("=== SIGNAL TIER DISTRIBUTION ===")
    tier_counts = sample['signal_tier'].value_counts()
    for tier, count in tier_counts.items():
        pct = 100 * count / len(sample)
        print(f"  {tier:<15}: {count:>3} ({pct:.1f}%)")
    print()

    # Print examples for each non-CLEAN tier
    print("=== FLAGGED PR EXAMPLES ===")
    for tier in ['EXPLICIT', 'GENERATED', 'SUSPICIOUS']:
        tier_prs = sample[sample['signal_tier'] == tier]
        if len(tier_prs) == 0:
            continue
        print(f"\n{tier} ({len(tier_prs)} PRs):")
        for _, row in tier_prs.head(3).iterrows():
            print(f"  {row['slug']} PR#{row['number']}")
            print(f"  URL: {row['github_url']}")
            print(f"  Signals: {row['signals_found'][:100]}")
            print(f"  Title: {row['title'][:80]}")
            print()

    # Contamination rate estimates
    print("=== CONTAMINATION RATE ESTIMATES ===")
    conservative = estimate_contamination(sample, count_suspicious=False)
    upper_bound  = estimate_contamination(sample, count_suspicious=True)

    print(f"\nConservative (EXPLICIT + GENERATED only):")
    print(f"  Rate: {conservative['rate']*100:.1f}% "
          f"(95% CI: {conservative['ci_lower']*100:.1f}% – "
          f"{conservative['ci_upper']*100:.1f}%)")
    print(f"  N contaminated: {conservative['n_contaminated']} / {conservative['n_sampled']}")

    print(f"\nUpper bound (+ SUSPICIOUS):")
    print(f"  Rate: {upper_bound['rate']*100:.1f}% "
          f"(95% CI: {upper_bound['ci_lower']*100:.1f}% – "
          f"{upper_bound['ci_upper']*100:.1f}%)")
    print(f"  N contaminated: {upper_bound['n_contaminated']} / {upper_bound['n_sampled']}")

    # PRs requiring manual review
    manual = sample[sample['manual_review'] == True]
    print(f"\nPRs flagged for manual review: {len(manual)}")
    print(f"(URLs exported to {OUTPUT_FULL} for inspection)")

    # Save outputs
    output_cols = [
        'slug', 'number', 'title', 'user', 'github_url',
        'signal_tier', 'signals_found', 'notes', 'manual_review',
        'created_at', 'merged_at', 'body'
    ]
    output_cols = [c for c in output_cols if c in sample.columns]
    sample[output_cols].to_csv(OUTPUT_FULL, index=False)

    summary_rows = [conservative, upper_bound]
    pd.DataFrame(summary_rows).to_csv(OUTPUT_SUMMARY, index=False)

    print(f"\nFull sample saved to  : {OUTPUT_FULL}")
    print(f"Summary saved to      : {OUTPUT_SUMMARY}")
    print()
    print("=" * 70)
    print("NEXT STEP: Manual Review")
    print("=" * 70)
    print(f"Open {OUTPUT_FULL} and review the {len(manual)} flagged PRs.")
    print("For each flagged PR, visit the GitHub URL and verify:")
    print("  1. Does the PR body contain AI-generated content?")
    print("  2. Does the commit history show AI tool usage?")
    print("  3. Is this genuinely a human-authored PR?")
    print()
    print("Update the 'manual_review_verdict' column:")
    print("  CONFIRMED_AI  - AI assistance confirmed")
    print("  CONFIRMED_HUMAN - Human-authored, signal was false positive")
    print("  UNCERTAIN     - Cannot determine from available evidence")
    print()
    print("After manual review, re-run contamination estimate using")
    print("manual verdicts for the final paper figures.")


