INPUT_REPOS  = Path("data/aidev_filtered_v1.csv")
INPUT_HUMAN  = Path("data/human_pull_request.parquet")
OUTPUT_FULL  = Path("data/attribution_validation.csv")
OUTPUT_SUMMARY = Path("data/attribution_summary.csv")

# Sample size — 200 PRs gives a margin of error of ~7% at 95% CI
# for a binary proportion (worst case p=0.5)
SAMPLE_SIZE = 200
RANDOM_SEED = 42


# =============================================================================
# SIGNAL DETECTION PATTERNS
# =============================================================================

# Tools that generate PR descriptions or summaries automatically
# These leave distinctive signatures in the PR body
AI_DESCRIPTION_TOOLS = [
    # Explicit tool attribution patterns
    r'this (pr )?description was (created|generated) by',
    r'summary generated by',
    r'(auto|automatically) generated (by|using|with)',
    r'generated with (the help of|assistance from|)?ai',
    r'\bcodex\b.*generated',
    r'written by (an )?ai',

    # Known AI PR description tools
    r'ellipsis\.dev',
    r'coderabbit\.ai',
    r'sweep\.dev',
    r'bloop\.ai',
    r'linearb\.io',
    r'sourcegraph\.com/cody',
    r'what-the-diff',
    r'pr-agent',
    r'openai\.com.*description',
    r'gitguardian',
]

# Explicit AI authorship attribution — strongest signal
EXPLICIT_AI_SIGNALS = [
    # Standard git co-authorship used by AI tools
    r'co-authored-by:\s*(claude|copilot|cursor|chatgpt|gpt-4|gpt4|openai'
    r'|devin|codex|codewhisperer|cody|tabnine|kite|replit)',

    # Common AI tool self-attribution patterns
    r'generated by (claude|copilot|cursor|chatgpt|gpt|openai|devin|codex)',
    r'(claude|copilot|cursor|chatgpt|gpt-4)\s*(generated|wrote|authored|created)',
    r'with (the )?(help|assistance) of (claude|copilot|cursor|chatgpt|gpt)',
    r'using (claude|copilot|cursor|chatgpt|gpt-4|openai)',
    r'ai[- ]generated (code|changes|implementation|solution)',
    r'(claude|copilot|cursor|chatgpt)\s*:',  # tool name as prefix

    # Anthropic/OpenAI/GitHub attribution
    r'anthropic',
    r'openai',
    r'\bgithub copilot\b',
    r'\bclaude\s+(sonnet|opus|haiku|code)\b',
]

# Structural patterns characteristic of AI-generated PR descriptions
# These are present when developers paste AI output directly
STRUCTURAL_AI_PATTERNS = [
    # The hierarchical summary format used by Ellipsis, PR-Agent, etc.
    r'##\s*(summary|overview|changes|what.*changed)',
    r'>\s*\[!important\]',           # GitHub admonition used by Ellipsis
    r'-\s+\*\*(behavior|changes|dependencies|documentation|type|scope)\*\*:',

    # Checklist formats common in AI-generated descriptions
    r'- \[x\].*\n- \[x\].*\n- \[x\]',  # multiple pre-checked items

    # Token-characteristic phrases
    r'this (pr|pull request|commit|change) (introduces|implements|adds|fixes|refactors)',
    r'(the following|below) (changes|modifications) (were|have been) made',
    r'key (changes|modifications|updates) in this (pr|pull request)',
]

# Suspicious signals — weaker, require manual judgment
SUSPICIOUS_SIGNALS = [
    # Unusually structured descriptions for a development PR
    r'(problem|solution|approach|implementation|testing|notes?):',

    # AI tool mentions that might be incidental
    r'\bcopilot\b',
    r'\bcursor\b',
    r'\bchatgpt\b',
    r'\bgpt-4\b',
    r'\bclaude\b',

    # Bot-like username patterns
    # (checked separately against user field)
]

# Bot username patterns — applied to the user field
BOT_USERNAME_PATTERNS = [
    r'bot$',
    r'-bot$',
    r'bot-',
    r'\[bot\]',
    r'automation',
    r'auto-',
    r'dependabot',
    r'renovate',
    r'github-actions',
    r'sweep-ai',
    r'coderabbit',
]


# =============================================================================
# SIGNAL DETECTION FUNCTIONS
# =============================================================================

def check_patterns(text: str, patterns: List[str]) -> List[str]:
    """Return list of pattern matches found in text."""
    if not text:
        return []
    text_lower = text.lower()
    matched = []
    for pattern in patterns:
        if re.search(pattern, text_lower, re.IGNORECASE | re.MULTILINE):
            matched.append(pattern[:50])  # truncate for readability
    return matched


def is_bot_username(username: str) -> bool:
    """Check if a username matches known bot patterns."""
    if not username:
        return False
    username_lower = str(username).lower()
    return any(re.search(p, username_lower) for p in BOT_USERNAME_PATTERNS)


def classify_pr(row: pd.Series) -> Dict:
    """
    Classify a PR by AI-assistance signal strength.

    Returns a dict with:
        signal_tier     - EXPLICIT / GENERATED / SUSPICIOUS / CLEAN
        signals_found   - list of matched patterns
        notes           - human-readable explanation
        manual_review   - bool, whether manual review is recommended
    """
    body  = str(row.get('body', '') or '')
    title = str(row.get('title', '') or '')
    user  = str(row.get('user', '') or '')

    combined_text = f"{title}\n{body}"

    signals_found = []
    signal_tier   = 'CLEAN'

    # --- Check explicit AI signals (strongest) ---
    explicit_matches = check_patterns(combined_text, EXPLICIT_AI_SIGNALS)
    if explicit_matches:
        signals_found.extend([f'EXPLICIT:{m}' for m in explicit_matches])
        signal_tier = 'EXPLICIT'

    # --- Check AI description tool signatures ---
    if signal_tier != 'EXPLICIT':
        generated_matches = check_patterns(combined_text, AI_DESCRIPTION_TOOLS)
        if generated_matches:
            signals_found.extend([f'GENERATED:{m}' for m in generated_matches])
            signal_tier = 'GENERATED'

    # --- Check structural AI patterns ---
    if signal_tier == 'CLEAN':
        structural_matches = check_patterns(combined_text, STRUCTURAL_AI_PATTERNS)
        if len(structural_matches) >= 2:
            # Require at least 2 structural signals to avoid false positives
            signals_found.extend([f'STRUCTURAL:{m}' for m in structural_matches])
            signal_tier = 'SUSPICIOUS'

    # --- Check suspicious signals ---
    if signal_tier == 'CLEAN':
        suspicious_matches = check_patterns(combined_text, SUSPICIOUS_SIGNALS)
        if suspicious_matches:
            signals_found.extend([f'SUSPICIOUS:{m}' for m in suspicious_matches])
            signal_tier = 'SUSPICIOUS'

    # --- Check bot username ---
    if is_bot_username(user):
        signals_found.append(f'BOT_USERNAME:{user}')
        if signal_tier == 'CLEAN':
            signal_tier = 'SUSPICIOUS'

    # --- Check empty body (no description = can't assess) ---
    if not body.strip() or body.strip() in ('nan', 'None', ''):
        signals_found.append('EMPTY_BODY')
        if signal_tier == 'CLEAN':
            signal_tier = 'SUSPICIOUS'  # Can't rule out AI, flag for manual

    notes = _build_notes(signal_tier, signals_found, body)
    manual_review = signal_tier in ('EXPLICIT', 'GENERATED', 'SUSPICIOUS')

    return {
        'signal_tier':   signal_tier,
        'signals_found': ' | '.join(signals_found) if signals_found else 'none',
        'notes':         notes,
        'manual_review': manual_review,
    }


def _build_notes(tier: str, signals: List[str], body: str) -> str:
    """Build a human-readable explanation of the classification."""
    if tier == 'EXPLICIT':
        return 'Explicit AI tool attribution found in PR body or title'
    if tier == 'GENERATED':
        return 'AI PR description tool signature detected in body'
    if tier == 'SUSPICIOUS':
        if 'EMPTY_BODY' in ' '.join(signals):
            return 'Empty PR body — cannot assess AI assistance'
        if any('BOT_USERNAME' in s for s in signals):
            return 'Bot-like username detected'
        return 'Indirect AI signals — manual review recommended'
    return 'No detectable AI signals in PR metadata'


# =============================================================================
# SAMPLING
# =============================================================================

def stratified_sample(
    df: pd.DataFrame,
    n: int,
    stratum_col: str,
    seed: int = 42
) -> pd.DataFrame:
    """
    Sample n PRs stratified by stratum_col (repository slug).

    Uses proportional allocation — each repo contributes PRs proportional
    to its share of the total, with a minimum of 1 per repo.
    """
    rng = np.random.default_rng(seed)
    total = len(df)
    samples = []

    for slug, group in df.groupby(stratum_col):
        # Proportional allocation
        n_from_repo = max(1, round(n * len(group) / total))
        n_from_repo = min(n_from_repo, len(group))
        idx = rng.choice(len(group), size=n_from_repo, replace=False)
        samples.append(group.iloc[idx])

    sampled = pd.concat(samples, ignore_index=True)

    # Trim or top-up to exactly n
    if len(sampled) > n:
        sampled = sampled.sample(n=n, random_state=seed)
    elif len(sampled) < n:
        # Top up from unsampled PRs
        sampled_ids = set(sampled['id'])
        remaining   = df[~df['id'].isin(sampled_ids)]
        if len(remaining) > 0:
            extra = remaining.sample(
                n=min(n - len(sampled), len(remaining)),
                random_state=seed
            )
            sampled = pd.concat([sampled, extra], ignore_index=True)

    return sampled.reset_index(drop=True)


# =============================================================================
# CONTAMINATION RATE ESTIMATION
# =============================================================================

def estimate_contamination(
    df: pd.DataFrame,
    count_suspicious: bool = False
) -> Dict:
    """
    Estimate contamination rate with 95% Wilson confidence interval.

    The Wilson interval is preferred over normal approximation for
    proportions, especially when p is near 0 or 1.

    Args:
        df:                 Classified sample DataFrame
        count_suspicious:   If True, include SUSPICIOUS in contamination count
                            (upper bound estimate)

    Returns:
        Dict with rate, ci_lower, ci_upper, n, n_contaminated
    """
    n = len(df)

    if count_suspicious:
        n_contaminated = (
            df['signal_tier'].isin(['EXPLICIT', 'GENERATED', 'SUSPICIOUS'])
        ).sum()
        label = 'upper_bound (incl. SUSPICIOUS)'
    else:
        n_contaminated = (
            df['signal_tier'].isin(['EXPLICIT', 'GENERATED'])
        ).sum()
        label = 'conservative (EXPLICIT + GENERATED only)'

    # Wilson confidence interval
    ci = proportion_confint(
        count=n_contaminated,
        nobs=n,
        alpha=0.05,
        method='wilson'
    )

    return {
        'estimate_type':  label,
        'n_sampled':      n,
        'n_contaminated': int(n_contaminated),
        'rate':           round(n_contaminated / n, 4),
        'ci_lower':       round(ci[0], 4),
        'ci_upper':       round(ci[1], 4),
        'ci_method':      'Wilson 95%',
    }


