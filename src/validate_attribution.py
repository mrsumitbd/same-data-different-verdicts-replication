"""
validate_attribution.py

Estimates the contamination rate of the "human" baseline in our survival
analysis dataset. The human baseline is defined as PRs NOT flagged by
AIDev's agent detection heuristics. However, in 2024-2025, developers
routinely use AI tools locally (Copilot inline suggestions, Cursor edits,
ChatGPT-assisted code) without any detectable PR-level signal.

This script:
1. Samples human PRs from the cohort (stratified by repository)
2. Applies automated AI-signal detection to each PR's metadata
3. Categorizes each PR into signal strength tiers
4. Produces a contamination rate estimate with 95% confidence interval
5. Exports flagged PRs for manual review with GitHub URLs

Contamination signals detected (PR metadata only — no code diff access):
    EXPLICIT   - AI tool explicitly credited in PR body or title
    GENERATED  - AI PR description tool signature detected
    SUSPICIOUS - Indirect signals suggesting AI assistance
    CLEAN      - No detectable AI signals

The contamination rate is defined as the proportion of human-baseline PRs
showing EXPLICIT or GENERATED signals. SUSPICIOUS cases are reported
separately as a potential lower bound.

Usage:
    python src/validate_attribution.py

Input:
    data/aidev_filtered_v1.csv
    data/human_pull_request.parquet

Output:
    data/attribution_validation.csv   - full sample with signal classification
    data/attribution_summary.csv      - contamination rate with CI
"""

